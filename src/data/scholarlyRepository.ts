/**
 * Returns the current ISO-8601 week number (1-53)
 */
export function getIsoWeekNumber(d: Date = new Date()): number {
  const date = new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
  const dayNum = date.getUTCDay() || 7;
  date.setUTCDate(date.getUTCDate() + 4 - dayNum);
  const yearStart = new Date(Date.UTC(date.getUTCFullYear(), 0, 1));
  return Math.ceil((((date.getTime() - yearStart.getTime()) / 86400000) + 1) / 7);
}

/**
 * Rotates the 100+ repository deterministically based on the current week number.
 * Marks 12 spotlight papers for the active week while preserving the complete repository.
 */
export function getWeeklyRotatedRepository(weekOffset: number = 0): {
  papers: ScholarlyPaper[];
  weeklySpotlightPapers: ScholarlyPaper[];
  currentWeek: number;
  totalVerifiedCount: number;
  recentFiveYearPercentage: number;
} {
  const baseWeek = getIsoWeekNumber();
  const activeWeek = ((baseWeek + weekOffset - 1) % 52) + 1;

  // Total papers count
  const totalVerifiedCount = SCHOLARLY_PAPERS.length;

  // Count papers from last 5 years (2021-2026)
  const currentYear = new Date().getFullYear();
  const recentPapers = SCHOLARLY_PAPERS.filter(p => p.year >= currentYear - 5);
  const recentFiveYearPercentage = Math.round((recentPapers.length / totalVerifiedCount) * 100);

  // Deterministic rotation seed: select 12 papers for the week spotlight
  const spotlightCount = 12;
  const startIndex = ((activeWeek * 7) % totalVerifiedCount);

  const spotlightIds = new Set<string>();
  for (let i = 0; i < spotlightCount; i++) {
    const idx = (startIndex + i * 5) % totalVerifiedCount;
    spotlightIds.add(SCHOLARLY_PAPERS[idx].id);
  }

  const papersWithSpotlight = SCHOLARLY_PAPERS.map(p => ({
    ...p,
    isWeeklySpotlight: spotlightIds.has(p.id)
  }));

  const weeklySpotlightPapers = papersWithSpotlight.filter(p => p.isWeeklySpotlight);

  return {
    papers: papersWithSpotlight,
    weeklySpotlightPapers,
    currentWeek: activeWeek,
    totalVerifiedCount,
    recentFiveYearPercentage
  };
}

/**
 * Generates an APA 7th Edition formatted citation for any paper
 */
export function generateApaCitation(paper: ScholarlyPaper): string {
  const authorsStr = paper.authors.join(', ');
  return `${authorsStr} (${paper.year}). ${paper.title}. ${paper.journal}. https://doi.org/${paper.doi}`;
}

/**
 * Generates a BibTeX entry for scholarly export
 */
export function generateBibtex(paper: ScholarlyPaper): string {
  const firstAuthor = paper.authors[0]?.split(',')[0]?.trim().toLowerCase() || 'author';
  const citationKey = `${firstAuthor}${paper.year}${paper.ralPhase.toLowerCase()}`;
  return `@article{${citationKey},
  author  = {${paper.authors.join(' and ')}},
  title   = {${paper.title}},
  journal = {${paper.journal}},
  year    = {${paper.year}},
  doi     = {${paper.doi}}
}`;
}
